package com.finsec.fuse.reimplementation.auth;

import java.nio.charset.StandardCharsets;
import java.security.MessageDigest;
import java.util.Arrays;
import java.util.HexFormat;
import java.util.UUID;
import org.junit.jupiter.api.Test;
import static org.junit.jupiter.api.Assertions.*;

class SyntheticGrantV2DetachedMacTest {
    private static final SyntheticGrantV2DetachedMac.Profile PROFILE =
            new SyntheticGrantV2DetachedMac.Profile(32, 1024, 24598);
    private static byte[] filled(int length, int value) {
        byte[] result = new byte[length]; Arrays.fill(result, (byte) value); return result;
    }
    // Independent test-only SHA256/ipad/opad reference; never product crypto implementation.
    private static byte[] reference(byte[] key, byte[] data) throws Exception {
        byte[] effective = key.length > 64 ? MessageDigest.getInstance("SHA-256").digest(key) : key.clone();
        byte[] inner = filled(64, 0x36), outer = filled(64, 0x5c);
        for (int i = 0; i < effective.length; i++) { inner[i] ^= effective[i]; outer[i] ^= effective[i]; }
        var sha = MessageDigest.getInstance("SHA-256");
        sha.update(inner); byte[] inside = sha.digest(data);
        sha.update(outer); return sha.digest(inside);
    }
    private static void goldenReference() throws Exception {
        // RFC4231 case6, literal published expected result (not generated by the utility).
        assertEquals("60e431591ee0b67f0d8a26aacbf5b77f8e0bc6213728c5140546040f0ee37f54",
                HexFormat.of().formatHex(reference(filled(131, 0xaa),
                        "Test Using Larger Than Block-Size Key - Hash Key First".getBytes(StandardCharsets.US_ASCII))));
    }
    private static UUID id(int n) { return new UUID(0, n); }
    private static SyntheticGrantV2Codec.Prepared prepared(String intent) {
        var action = new SyntheticGrantV2Codec.Action(id(1), id(2), 1,
                GrantStorageShape.AllowedAction.EVALUATE_KYC, "synthetic-customer",
                9007199254740993L, id(3), id(4), null, null, null, "synthetic-policy");
        // Existing independently pinned codec action literal digest, no MAC calculation.
        var claims = new SyntheticGrantV2Codec.Claims("FUSE-GRANT-v2", "HMAC-SHA256",
                "synthetic-key", id(5), id(2), 1, id(6), "synthetic-principal", intent,
                "synthetic-issuer", "synthetic-source", "synthetic-target", null, id(4),
                action.allowedAction(), action.customerId(), action.amountKrw(), id(3), null,
                null, null, 1, id(1), "90c64612a43f403c5cb7d6ef90f2d6a8619913889ed328cb4cc808f02640b365",
                "synthetic-policy", id(7), null, 100, 400);
        return SyntheticGrantV2Codec.prepare(new SyntheticGrantV2Codec.Profile(16384,8192,8,64,1000,300), claims, action);
    }
    @Test void referenceIsGoldenAndPreparedFrameMatches() throws Exception {
        goldenReference(); var p = prepared("synthetic-intent"); byte[] key = filled(131, 0xaa);
        assertTrue(SyntheticGrantV2DetachedMac.matches(PROFILE, p, key, reference(key, p.unsignedFrame())));
    }
    @Test void wrongKeyFrameAndEveryTagByteFail() throws Exception {
        goldenReference(); var p = prepared("synthetic-intent"); byte[] key = filled(32, 7);
        byte[] tag = reference(key, p.unsignedFrame()), wrongKey = key.clone(); wrongKey[0] ^= 1;
        assertFalse(SyntheticGrantV2DetachedMac.matches(PROFILE, p, wrongKey, tag));
        assertFalse(SyntheticGrantV2DetachedMac.matches(PROFILE, prepared("synthetic-other"), key, tag));
        for (int i=0;i<32;i++) { byte[] bad=tag.clone(); bad[i]^=1;
            assertFalse(SyntheticGrantV2DetachedMac.matches(PROFILE,p,key,bad)); }
    }
    @Test void inputsStayUnchangedAndPreparedCopiesCannotMutateFrame() throws Exception {
        goldenReference(); var p=prepared("synthetic-intent"); byte[] key=filled(32,9), frame=p.unsignedFrame();
        byte[] tag=reference(key,frame), savedKey=key.clone(), savedTag=tag.clone();
        Arrays.fill(p.unsignedFrame(),(byte)0);
        assertTrue(SyntheticGrantV2DetachedMac.matches(PROFILE,p,key,tag));
        assertArrayEquals(savedKey,key); assertArrayEquals(savedTag,tag); assertArrayEquals(frame,p.unsignedFrame());
    }
    @Test void inputAndProfileBoundariesFailWithFixedRedactedError() throws Exception {
        var p=prepared("synthetic-intent"); byte[] key=filled(32,1), tag=new byte[32];
        invalid(() -> SyntheticGrantV2DetachedMac.matches(null,p,key,tag));
        invalid(() -> SyntheticGrantV2DetachedMac.matches(PROFILE,null,key,tag));
        invalid(() -> SyntheticGrantV2DetachedMac.matches(PROFILE,p,null,tag));
        invalid(() -> SyntheticGrantV2DetachedMac.matches(PROFILE,p,key,null));
        for(int n:new int[]{0,31,1025}) invalid(() -> SyntheticGrantV2DetachedMac.matches(PROFILE,p,new byte[n],tag));
        for(int n:new int[]{0,31,33}) invalid(() -> SyntheticGrantV2DetachedMac.matches(PROFILE,p,key,new byte[n]));
        invalid(() -> new SyntheticGrantV2DetachedMac.Profile(31,1024,24598));
        invalid(() -> new SyntheticGrantV2DetachedMac.Profile(33,32,24598));
        invalid(() -> new SyntheticGrantV2DetachedMac.Profile(32,1025,24598));
        invalid(() -> new SyntheticGrantV2DetachedMac.Profile(32,1024,0));
        invalid(() -> new SyntheticGrantV2DetachedMac.Profile(32,1024,24599));
        invalid(() -> SyntheticGrantV2DetachedMac.matches(new SyntheticGrantV2DetachedMac.Profile(32,1024,p.unsignedFrame().length-1),p,key,tag));
        goldenReference();
        assertTrue(SyntheticGrantV2DetachedMac.matches(new SyntheticGrantV2DetachedMac.Profile(32,32,p.unsignedFrame().length),p,key,reference(key,p.unsignedFrame())));
        byte[] maxKey=filled(1024,3);
        assertTrue(SyntheticGrantV2DetachedMac.matches(PROFILE,p,maxKey,reference(maxKey,p.unsignedFrame())));
    }
    private static void invalid(org.junit.jupiter.api.function.Executable work) {
        var error=assertThrows(IllegalArgumentException.class,work);
        assertEquals("INVALID_SYNTHETIC_DETACHED_MAC_INPUT",error.getMessage()); assertNull(error.getCause());
    }
    @Test void providerCheckedAndRuntimeFailuresAreRedactedWithoutGlobalRegistration() {
        for (boolean checked : new boolean[]{false,true}) {
            var error = assertThrows(IllegalStateException.class, () ->
                    SyntheticGrantV2DetachedMac.compareMac(() -> {
                        if (checked) throw new java.security.NoSuchAlgorithmException("SYNTHETIC_RAW_CANARY");
                        throw new java.security.ProviderException("SYNTHETIC_RAW_CANARY");
                    }, new byte[32], new byte[1], new byte[32]));
            assertEquals("SYNTHETIC_DETACHED_MAC_UNAVAILABLE",error.getMessage());
            assertNull(error.getCause());
        }
        for (boolean failInit : new boolean[]{true,false}) {
            var error = assertThrows(IllegalStateException.class, () ->
                    SyntheticGrantV2DetachedMac.compareMac(() -> new FailingMac(failInit),
                            new byte[32],new byte[1],new byte[32]));
            assertEquals("SYNTHETIC_DETACHED_MAC_UNAVAILABLE",error.getMessage());
            assertNull(error.getCause());
        }
    }
    private static final class FailingMac extends javax.crypto.Mac {
        FailingMac(boolean failInit) { super(new FailingSpi(failInit),null,"HmacSHA256"); }
    }
    private static final class FailingSpi extends javax.crypto.MacSpi {
        private final boolean failInit;
        FailingSpi(boolean failInit) { this.failInit=failInit; }
        protected int engineGetMacLength() { return 32; }
        protected void engineInit(java.security.Key key, java.security.spec.AlgorithmParameterSpec params) {
            if(failInit) throw new java.security.ProviderException("SYNTHETIC_RAW_CANARY");
        }
        protected void engineUpdate(byte value) {}
        protected void engineUpdate(byte[] value,int offset,int length) {}
        protected byte[] engineDoFinal() { throw new java.security.ProviderException("SYNTHETIC_RAW_CANARY"); }
        protected void engineReset() {}
    }
}
